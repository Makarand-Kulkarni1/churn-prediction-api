"""
Churn Prediction API
---------------------
Serves the XGBoost model trained in Churn_Prediction_Project.ipynb.

Run locally:
    uvicorn app:app --reload

Interactive docs (auto-generated by FastAPI):
    http://127.0.0.1:8000/docs
"""

from typing import Literal

import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# 1. Load the trained model + the exact column order it was trained on.
#    Both files are produced by the notebook's "Save the Model" cell.
#    Loading happens once, at startup — not per-request — so predictions stay fast.
# ---------------------------------------------------------------------------
MODEL_PATH = "model/churn_model.pkl"
COLUMNS_PATH = "model/model_columns.pkl"
DECISION_THRESHOLD = 0.35  # chosen in the notebook's threshold-tuning section

try:
    model = joblib.load(MODEL_PATH)
    model_columns = joblib.load(COLUMNS_PATH)
except FileNotFoundError as e:
    raise RuntimeError(
        f"Could not load model artifacts ({e}). "
        f"Make sure churn_model.pkl and model_columns.pkl are in the model/ directory."
    )

app = FastAPI(
    title="Customer Churn Prediction API",
    description="Predicts the probability that a telecom customer will churn.",
    version="1.0.0",
)


# ---------------------------------------------------------------------------
# 2. Pydantic model — this is the contract for what a valid request looks like.
#    It mirrors the RAW columns from Telco-Customer-Churn.csv (minus customerID
#    and Churn, since those aren't real inputs). FastAPI validates every
#    incoming request against this automatically, before your code ever runs.
#
#    Literal[...] restricts a field to an exact set of allowed strings —
#    e.g. someone sending "internet_service": "Fibre" instead of "Fiber optic"
#    gets a clear 422 error immediately, instead of silently producing a
#    garbage prediction downstream.
# ---------------------------------------------------------------------------
class CustomerData(BaseModel):
    gender: Literal["Male", "Female"]
    SeniorCitizen: Literal[0, 1] = Field(..., description="1 = senior citizen, 0 = not")
    Partner: Literal["Yes", "No"]
    Dependents: Literal["Yes", "No"]
    tenure: int = Field(..., ge=0, description="Months the customer has stayed")
    PhoneService: Literal["Yes", "No"]
    MultipleLines: Literal["Yes", "No", "No phone service"]
    InternetService: Literal["DSL", "Fiber optic", "No"]
    OnlineSecurity: Literal["Yes", "No", "No internet service"]
    OnlineBackup: Literal["Yes", "No", "No internet service"]
    DeviceProtection: Literal["Yes", "No", "No internet service"]
    TechSupport: Literal["Yes", "No", "No internet service"]
    StreamingTV: Literal["Yes", "No", "No internet service"]
    StreamingMovies: Literal["Yes", "No", "No internet service"]
    Contract: Literal["Month-to-month", "One year", "Two year"]
    PaperlessBilling: Literal["Yes", "No"]
    PaymentMethod: Literal[
        "Electronic check",
        "Mailed check",
        "Bank transfer (automatic)",
        "Credit card (automatic)",
    ]
    MonthlyCharges: float = Field(..., ge=0)
    TotalCharges: float = Field(..., ge=0)

    class Config:
        json_schema_extra = {
            "example": {
                "gender": "Female",
                "SeniorCitizen": 0,
                "Partner": "Yes",
                "Dependents": "No",
                "tenure": 1,
                "PhoneService": "No",
                "MultipleLines": "No phone service",
                "InternetService": "DSL",
                "OnlineSecurity": "No",
                "OnlineBackup": "Yes",
                "DeviceProtection": "No",
                "TechSupport": "No",
                "StreamingTV": "No",
                "StreamingMovies": "No",
                "Contract": "Month-to-month",
                "PaperlessBilling": "Yes",
                "PaymentMethod": "Electronic check",
                "MonthlyCharges": 29.85,
                "TotalCharges": 29.85,
            }
        }


class PredictionResponse(BaseModel):
    churn_probability: float
    churn_prediction: Literal["Yes", "No"]
    decision_threshold: float
    recommendation: str


# ---------------------------------------------------------------------------
# 3. Preprocessing — must mirror the notebook EXACTLY (same maps, same
#    one-hot columns, same fillna strategy), or the model will silently
#    see garbage at inference time.
# ---------------------------------------------------------------------------
BINARY_MAP = {"Yes": 1, "No": 0}
GENDER_MAP = {"Male": 1, "Female": 0}

NOMINAL_COLS = [
    "MultipleLines", "InternetService", "OnlineSecurity", "OnlineBackup",
    "DeviceProtection", "TechSupport", "StreamingTV", "StreamingMovies",
    "Contract", "PaymentMethod",
]


def preprocess(customer: CustomerData) -> pd.DataFrame:
    row = customer.model_dump()
    df = pd.DataFrame([row])

    # Binary Yes/No -> 1/0, same explicit mapping as the notebook
    df["gender"] = df["gender"].map(GENDER_MAP)
    for col in ["Partner", "Dependents", "PhoneService", "PaperlessBilling"]:
        df[col] = df[col].map(BINARY_MAP)

    # One-hot encode the nominal columns
    df = pd.get_dummies(df, columns=NOMINAL_COLS)

    # Align to the exact column set/order the model was trained on.
    # Any dummy column that doesn't appear for this single row (e.g. this
    # customer's InternetService wasn't "Fiber optic") gets filled with 0,
    # and columns are put back in the model's expected order.
    df = df.reindex(columns=model_columns, fill_value=0)

    return df


# ---------------------------------------------------------------------------
# 4. Endpoints
# ---------------------------------------------------------------------------
@app.get("/")
def health_check():
    """Simple liveness check — confirms the service and model are up."""
    return {"status": "ok", "model_loaded": model is not None}


@app.post("/predict", response_model=PredictionResponse)
def predict(customer: CustomerData):
    """
    Accepts one customer's raw account/service data and returns:
    - the model's predicted churn probability
    - a Yes/No call at the business-chosen 0.35 threshold (see notebook Section 7)
    - a short recommendation for the retention team
    """
    try:
        X = preprocess(customer)
        probability = float(model.predict_proba(X)[:, 1][0])
    except Exception as e:
        # Anything that goes wrong here is a server-side/data problem,
        # not a validation problem (Pydantic already handled that).
        raise HTTPException(status_code=500, detail=f"Prediction failed: {e}")

    will_churn = probability >= DECISION_THRESHOLD

    if will_churn:
        recommendation = (
            "High churn risk — flag for proactive retention outreach "
            "(e.g. loyalty offer, contract upgrade incentive)."
        )
    else:
        recommendation = "Low churn risk — no action needed at this time."

    return PredictionResponse(
        churn_probability=round(probability, 4),
        churn_prediction="Yes" if will_churn else "No",
        decision_threshold=DECISION_THRESHOLD,
        recommendation=recommendation,
    )
